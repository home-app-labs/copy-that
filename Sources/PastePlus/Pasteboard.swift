import AppKit
import ImageIO

/// Watches the general pasteboard and turns new contents into history items.
final class PasteboardWatcher {
    static let shared = PasteboardWatcher()

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Markers apps put on the pasteboard for things that must not be recorded (passwords, one-time codes).
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]
    private static let maxTextBytes = 2_000_000
    private static let maxImageBytes = 40_000_000

    func start() {
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard !AppSettings.shared.paused, var capture = Self.read(pasteboard) else { return }
        let app = NSWorkspace.shared.frontmostApplication
        if app?.bundleIdentifier != Bundle.main.bundleIdentifier {
            capture.appName = app?.localizedName
            capture.appBundleID = app?.bundleIdentifier
        }
        HistoryStore.shared.add(capture)
    }

    static func read(_ pasteboard: NSPasteboard) -> Capture? {
        let types = pasteboard.types ?? []
        if types.contains(where: { skipTypes.contains($0.rawValue) }) { return nil }

        // Files first: Finder also puts the file name and an icon on the pasteboard.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return Capture(kind: .file, text: urls.map(\.path).joined(separator: "\n"))
        }

        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
           string.utf8.count <= maxTextBytes {
            func rich(_ type: NSPasteboard.PasteboardType) -> Data? {
                guard types.contains(type), let data = pasteboard.data(forType: type),
                      data.count <= maxTextBytes else { return nil }
                return data
            }
            return .text(string, rtf: rich(.rtf), html: rich(.html))
        }

        if let png = imagePNG(from: pasteboard, types: types), png.count <= maxImageBytes {
            var capture = Capture(kind: .image, data: [BlobType.png: png])
            if let source = CGImageSourceCreateWithData(png as CFData, nil),
               let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any] {
                capture.pixelWidth = properties[kCGImagePropertyPixelWidth] as? Int
                capture.pixelHeight = properties[kCGImagePropertyPixelHeight] as? Int
            }
            return capture
        }
        return nil
    }

    private static func imagePNG(from pasteboard: NSPasteboard, types: [NSPasteboard.PasteboardType]) -> Data? {
        if types.contains(.png), let data = pasteboard.data(forType: .png) { return data }
        if types.contains(.tiff), let data = pasteboard.data(forType: .tiff),
           let rep = NSBitmapImageRep(data: data) {
            return rep.representation(using: .png, properties: [:])
        }
        return nil
    }

    // MARK: Writing back

    /// Puts an item back on the pasteboard without recording it as a new copy.
    func write(_ item: ClipItem, plainText: Bool = false) {
        let store = HistoryStore.shared
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link:
            if !plainText {
                if let rtf = store.blob(item, BlobType.rtf) { pasteboard.setData(rtf, forType: .rtf) }
                if let html = store.blob(item, BlobType.html) { pasteboard.setData(html, forType: .html) }
            }
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let png = store.blob(item, BlobType.png) {
                pasteboard.setData(png, forType: .png)
                if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation { pasteboard.setData(tiff, forType: .tiff) }
            }
        case .file:
            let urls = item.filePaths.map { URL(fileURLWithPath: $0) }
            if plainText || urls.isEmpty {
                pasteboard.setString(item.text ?? "", forType: .string)
            } else {
                pasteboard.writeObjects(urls as [NSURL])
            }
        }
        lastChangeCount = pasteboard.changeCount
        store.touch(item.id)
    }
}

/// Sends ⌘V to the frontmost app. Needs the Accessibility permission.
enum Paster {
    static var isTrusted: Bool { AXIsProcessTrusted() }

    /// Shows the system prompt that leads to Privacy & Security > Accessibility.
    static func requestTrust() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        _ = AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }

    static func sendPaste() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let keyV: CGKeyCode = 9
        for keyDown in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: keyV, keyDown: keyDown)
            event?.flags = .maskCommand
            event?.post(tap: .cgAnnotatedSessionEventTap)
        }
    }
}
